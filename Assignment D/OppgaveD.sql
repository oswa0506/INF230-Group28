-- PK = primaernøkkel, FK = fremmednøkkel
--
-- TABELL: explanation
--   explanation_id     PK    (hasExplanationID, f.eks. EXP-001)
--   description              (hasDescription)
--   explanation_type         (Counterfactual / Causal / Teleological / DeductiveNomological)
--
-- TABELL: audience
--   audience_id        PK
--   label
--   audience_name            (hasAudienceName)

-- TABELL: concept
--   concept_id         PK
--   label
--   concept_name             (hasConceptName)

-- TABELL: comprehensibility
--   property_id        PK
--   label
--   rating_label             (hasRatingLabel)
--   explanation_id     FK -> explanation   (hasProperty)
--
-- TABELL: explanation_audience   (isSuitableForAudience)
--   explanation_id     PK, FK -> explanation
--   audience_id        PK, FK -> audience
--
-- TABELL: explanation_concept    (isSuitableForTeaching)
--   explanation_id     PK, FK -> explanation
--   concept_id         PK, FK -> concept
--
-- TABELL: related_to             (relatedTo)
--   explanation_id_1   PK, FK -> explanation
--   explanation_id_2   PK, FK -> explanation
--
-- RELASJONER
--   explanation 1 --- N comprehensibility   (hver egenskap hoerer til en forklaring)
--   explanation N --- M audience            (via explanation_audience)
--   explanation N --- M concept             (via explanation_concept)
--   explanation N --- M explanation         (via related_to)
--
-- VALG
--   - Undertypene av Explanation er samlet i en kolonne (explanation_type).
--   - relatedTo er symmetrisk, derfor lagres hvert par bare en gang.
